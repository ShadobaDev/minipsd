"""Writes docs/COMPATIBILITY.md, the whole of it: what minipsd's reader does with every file of a
set of PSDs from other programs.

Each file goes through examples/read_file, whose output is parsed: the file is decoded, described
only (and why), or refused (and why); and the layer features minipsd reads as raw data without
applying them are counted.  The document is generated, never edited by hand: its text is here.
It carries no date, so regenerating it without a change to the reader leaves it the same.

Usage:
    python tools/compat_report.py <read_file executable> <directory of PSDs> <source name> <document>

For psd-tools' files (configure with -DMINIPSD_PSD_TOOLS_FILES=ON and build read_file first):
    python tools/compat_report.py build/msvc/examples/Debug/read_file.exe \\
        build/msvc/_deps/minipsd_psd_tools_files-src/tests/psd_files "psd-tools v1.25.0" docs/COMPATIBILITY.md

SPDX-License-Identifier: MIT
SPDX-FileCopyrightText: Copyright (c) 2026 Bartlomiej Mucha <shadobadev@gmail.com>
"""

import collections
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

INTRO = """\
<!-- Generated by tools/compat_report.py. DO NOT EDIT: change the script and run it again. -->

# Compatibility

What minipsd's reader does with PSD files saved by other programs: which it decodes, which it only
describes, which it refuses, and which features it reads without applying. The writer's own
output is covered by the golden test and the `psd-tools` round trip (see the spec's
[Verification](SPECIFICATION.md#verification)); this page is about everyone else's files.

This page is generated by [tools/compat_report.py](../tools/compat_report.py) with minipsd
{version}, over {count} files of {source}.

## Credits

The files come from **[psd-tools](https://github.com/psd-tools/psd-tools)**, the Python library
for reading Photoshop files (MIT licence), whose test suite collects PSDs from Photoshop and other
programs, covering every colour mode and depth, masks, groups, effects, text, smart objects and
blend modes. Thank you to its authors and contributors. psd-tools is also the independent reader
minipsd's writer is checked against.

The files are not copied into this repository: configure with `-DMINIPSD_PSD_TOOLS_FILES=ON` to
fetch them from a pinned psd-tools release, verified by its SHA-256.

## How to read the results

- **decoded:** 8- or 16-bit RGB. The header, resources and every layer record are read, and
  every layer's pixels and the composite are decoded. This is the subset minipsd supports today.
- **described:** another colour mode or depth, or ZIP-compressed layers (Photoshop's 16-bit
  ones). Everything but those pixels is read: size, colour mode, depth, dpi, ICC profile,
  resources, and every layer with its name, rectangle, opacity, visibility, blend mode and blocks.
  Decoding the pixels returns `MINIPSD_ERR_UNSUPPORTED`; ZIP channels are still copied when the
  file is read as a document with `stored` and written back. This is a choice of scope
  ([ROADMAP.md](ROADMAP.md), stage 6), not a failure.
- **refused:** the reader does not open the file, with the reason.
- **failed:** an error other than the above: a malformed file, or a bug. Each is listed. A
  malformed file that the tests know about is in `knownBad` in `tests/test_reader.cpp`, with the
  evidence; any other is a reader bug until shown otherwise.
- **Features read but not applied:** a layer is decoded as stored. Its blend mode, mask, group,
  effects or adjustment are handed over as raw data and not applied to its pixels. The composite
  is the saving program's own render, so a viewer that shows it shows them correctly.

## Regenerating

After a change to the reader:

```
cmake --preset msvc -DMINIPSD_PSD_TOOLS_FILES=ON
cmake --build --preset msvc --target read_file
python tools/compat_report.py build/msvc/examples/Debug/read_file.exe build/msvc/_deps/minipsd_psd_tools_files-src/tests/psd_files "psd-tools v1.25.0" docs/COMPATIBILITY.md
```

## Results
"""

# Additional-information blocks that carry a feature minipsd does not apply: it lists them as raw
# views (minipsd_layer_next_block), and decodes the layer's pixels as stored.
FEATURES = [
    ("Adjustment layers", {"levl", "curv", "brit", "blnc", "hue2", "hue ", "selc", "mixr", "grdm", "phfl",
                           "expA", "vibA", "thrs", "nvrt", "post", "clrL", "blwh"}),
    ("Fill layers (solid, gradient, pattern)", {"SoCo", "GdFl", "PtFl"}),
    ("Text layers", {"TySh", "tySh"}),
    ("Smart objects", {"SoLd", "SoLE", "PlLd", "plLd"}),
    ("Layer effects", {"lfx2", "lmfx", "lrFX"}),
    ("Vector masks and shapes", {"vmsk", "vsms", "vogk", "vscg", "vstk"}),
]

BLEND_NAMES = {
    "pass": "pass through", "norm": "normal", "diss": "dissolve", "dark": "darken", "mul ": "multiply",
    "idiv": "color burn", "lbrn": "linear burn", "dkCl": "darker color", "lite": "lighten", "scrn": "screen",
    "div ": "color dodge", "lddg": "linear dodge", "lgCl": "lighter color", "over": "overlay",
    "sLit": "soft light", "hLit": "hard light", "vLit": "vivid light", "lLit": "linear light",
    "pLit": "pin light", "hMix": "hard mix", "diff": "difference", "smud": "exclusion", "fsub": "subtract",
    "fdiv": "divide", "hue ": "hue", "sat ": "saturation", "colr": "color", "lum ": "luminosity",
}

HEADER = re.compile(r"^(\d+) x (\d+), (\d+)-bit (\S+), (\d+) channels")
LAYER = re.compile(r"^  \d+ '.*': \(-?\d+, -?\d+\)-\(-?\d+, -?\d+\), opacity \d+, (hidden|visible), blend (.{4})$")


class File:
    def __init__(self, path, root):
        self.name = path.relative_to(root).as_posix()
        self.refused = None          # why init refused the file
        self.mode = None             # "8-bit RGB", ...
        self.layers = 0
        self.layer_errors = []       # what failed while walking or decoding layers
        self.composite = None        # "decoded", "described", or what failed
        self.zip = 0                 # layers described only: ZIP-compressed
        self.blends = collections.Counter()
        self.features = collections.Counter()
        self.masks = 0
        self.others = 0              # layers with channels not read: alpha, spot
        self.groups = 0


def run(exe, path, root):
    f = File(path, root)
    out = subprocess.run([exe, str(path)], capture_output=True, text=True, errors="replace")
    lines = out.stdout.splitlines()
    if out.stderr.startswith("read_file: "):
        f.refused = out.stderr.strip()[len("read_file: "):]
        return f
    header = HEADER.match(lines[0]) if lines else None
    f.mode = f"{header.group(3)}-bit {header.group(4)}" if header else "?"
    in_composite = False
    for line in lines[1:]:
        m = LAYER.match(line)
        if m:
            f.layers += 1
            f.blends[m.group(2)] += 1
            continue
        if line.startswith("      blocks:"):
            parts = line[len("      blocks:"):].split(",")
            keys = parts[0].split()
            for key in keys:
                if key in ("lsct=1", "lsct=2"):
                    f.groups += 1
                for label, members in FEATURES:
                    if key in members or key.strip() in {m.strip() for m in members}:
                        f.features[label] += 1
            if any(p.strip() == "mask" for p in parts[1:]):
                f.masks += 1
            if "channels not read" in line:
                f.others += 1
            continue
        if "ZIP-compressed: described" in line and not in_composite:
            f.zip += 1
            continue
        if line.startswith("  layers: "):
            f.layer_errors.append(line.strip()[len("layers: "):])
            continue
        if line == "composite:":
            in_composite = True
            continue
        if "not decoded:" in line:
            reason = line.split("not decoded:", 1)[1].strip()
            if in_composite:
                f.composite = reason
            else:
                f.layer_errors.append(reason)
            continue
        if in_composite and f.composite is None:
            f.composite = "described" if "described, not decoded" in line else "decoded"
    return f


def status(f):
    if f.refused:
        return "refused", f.refused
    if f.layer_errors or (f.composite not in ("decoded", "described")):
        return "failed", "; ".join(f.layer_errors + ([f.composite] if f.composite not in ("decoded", "described") else []))
    if f.composite == "described":
        return "described", f"{f.mode}: pixels not decoded yet"
    if f.zip:
        return "described", f"{f.mode}: ZIP-compressed layers, copied, not decoded"
    return "decoded", ""


def report(files, source):
    out = []
    by_status = collections.Counter(status(f)[0] for f in files)
    out.append("| Result | Files | Meaning |")
    out.append("|---|---|---|")
    meaning = {
        "decoded": "every layer and the composite decoded to pixels",
        "described": "header, resources and layers read; pixels not decoded: outside 8- and 16-bit RGB, or ZIP",
        "refused": "the reader does not open the file (see below)",
        "failed": "malformed, or a reader bug (see below)",
    }
    for key in ("decoded", "described", "refused", "failed"):
        out.append(f"| {key} | {by_status[key]} | {meaning[key]} |")

    out.append("\n### By colour mode and depth\n")
    out.append("| Colour mode, depth | Files | Pixels |")
    out.append("|---|---|---|")
    modes = collections.Counter(f.mode for f in files if not f.refused)
    for mode, n in sorted(modes.items(), key=lambda kv: (-kv[1], kv[0])):
        decoded = sum(1 for f in files if f.mode == mode and status(f)[0] in ("decoded", "failed"))   # failed: listed below
        zipped = sum(1 for f in files if f.mode == mode and f.zip)
        pixels = ("decoded" if decoded == n else f"decoded, but ZIP-compressed layers in {zipped}" if decoded + zipped == n
                  else "not yet: described only" if not decoded else f"{decoded} decoded")
        out.append(f"| {mode} | {n} | {pixels} |")

    refused = collections.Counter(f.refused for f in files if f.refused)
    if refused:
        out.append("\n### Refused\n")
        out.append("| Reason | Files |")
        out.append("|---|---|")
        for reason, n in refused.most_common():
            out.append(f"| {reason} | {n} |")

    failed = [f for f in files if status(f)[0] == "failed"]
    out.append("\n### Failed\n")
    if failed:
        out.append("| File | Error | Why |")
        out.append("|---|---|---|")
        for f in failed:
            known = pathlib.PurePosixPath(f.name).name in KNOWN_BAD
            why = ("the file is malformed; the evidence is in `knownBad`, `tests/test_reader.cpp`" if known
                   else "**not explained yet: a reader bug until shown otherwise**")
            out.append(f"| `{f.name}` | {status(f)[1]} | {why} |")
    else:
        out.append("None.")

    out.append("\n### Layer features read but not applied\n")
    out.append("minipsd decodes each layer's pixels as stored and hands these features over as raw data "
               "(the blend key, `minipsd_layer_next_block`, a count of channels not read). The composite is "
               "the saving program's own render, so it shows them correctly.\n")
    out.append("| Feature | Layers | Files |")
    out.append("|---|---|---|")
    rows = []
    blends = collections.Counter()
    blend_files = collections.Counter()
    for f in files:
        for key, n in f.blends.items():
            if key != "norm":
                blends[key] += n
                blend_files[key] += 1
    rows.append(("Blend modes other than normal", sum(blends.values()),
                 sum(1 for f in files if any(k != "norm" for k in f.blends))))
    rows.append(("Layer groups", sum(f.groups for f in files), sum(1 for f in files if f.groups)))
    rows.append(("Layer masks", sum(f.masks for f in files), sum(1 for f in files if f.masks)))
    rows.append(("Other channels, not read (alpha, spot, CMYK's black)", sum(f.others for f in files), sum(1 for f in files if f.others)))
    for label, _ in FEATURES:
        rows.append((label, sum(f.features[label] for f in files), sum(1 for f in files if f.features[label])))
    for label, layers, nfiles in rows:
        out.append(f"| {label} | {layers} | {nfiles} |")
    if blends:
        out.append("\nBlend modes seen: " + ", ".join(
            f"{BLEND_NAMES.get(k, '?')} (`{k}`) {n}" for k, n in sorted(blends.items(), key=lambda kv: -kv[1])) + ".")

    out.append("\n<details><summary>Every file</summary>\n")
    out.append("| File | Result | Note |")
    out.append("|---|---|---|")
    for f in files:
        st, note = status(f)
        out.append(f"| `{f.name}` | {st} | {note} |")
    out.append("\n</details>")
    return "\n".join(out)


# The files the tests know to be malformed: named in knownBad in tests/test_reader.cpp.
KNOWN_BAD = set(re.findall(r'\{"([^"]+\.psd)", MINIPSD_ERR_',
                           (ROOT / "tests" / "test_reader.cpp").read_text(encoding="utf-8")))


def main():
    exe, root, source, doc = str(pathlib.Path(sys.argv[1]).resolve()), pathlib.Path(sys.argv[2]), sys.argv[3], pathlib.Path(sys.argv[4])
    paths = sorted(p for p in root.rglob("*") if p.suffix.lower() in (".psd", ".psb"))
    files = [run(exe, p, root) for p in paths]
    header = (ROOT / "include" / "minipsd.h").read_text(encoding="utf-8")
    version = ".".join(re.search(rf"#define MINIPSD_VERSION_{part} +(\d+)", header).group(1)
                       for part in ("MAJOR", "MINOR", "PATCH"))
    intro = INTRO.format(version=version, count=len(files), source=source)
    doc.write_text(intro + "\n" + report(files, source) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(files)} files: " + ", ".join(f"{k} {v}" for k, v in collections.Counter(status(f)[0] for f in files).items()))


if __name__ == "__main__":
    main()
